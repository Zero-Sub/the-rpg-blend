-- The reference schema name is RPGBA_CC. An instructor may require a learner-specific schema.
-- Do not add DROP statements to this file merely to make reruns convenient.

CREATE SCHEMA RPGBA_CC;

CREATE TABLE RPGBA_CC.CUSTOMER (
    CUSTOMER_ID      INTEGER      NOT NULL,
    CUSTOMER_NAME    VARCHAR(80)  NOT NULL,
    EMAIL            VARCHAR(120),
    LOYALTY_TIER     VARCHAR(10)  NOT NULL DEFAULT 'STANDARD',
    ACTIVE           CHAR(1)      NOT NULL DEFAULT 'Y',
    CONSTRAINT PK_CUSTOMER PRIMARY KEY (CUSTOMER_ID),
    CONSTRAINT CK_CUSTOMER_TIER CHECK (LOYALTY_TIER IN ('STANDARD', 'GOLD')),
    CONSTRAINT CK_CUSTOMER_ACTIVE CHECK (ACTIVE IN ('Y', 'N'))
);

CREATE TABLE RPGBA_CC.PRODUCT (
    PRODUCT_ID          INTEGER      NOT NULL,
    SKU                 VARCHAR(20)  NOT NULL,
    PRODUCT_NAME        VARCHAR(80)  NOT NULL,
    UNIT_PRICE          DECIMAL(9,2) NOT NULL,
    QUANTITY_AVAILABLE  INTEGER      NOT NULL DEFAULT 0,
    ACTIVE              CHAR(1)      NOT NULL DEFAULT 'Y',
    CONSTRAINT PK_PRODUCT PRIMARY KEY (PRODUCT_ID),
    CONSTRAINT UQ_PRODUCT_SKU UNIQUE (SKU),
    CONSTRAINT CK_PRODUCT_PRICE CHECK (UNIT_PRICE >= 0),
    CONSTRAINT CK_PRODUCT_QTY CHECK (QUANTITY_AVAILABLE >= 0),
    CONSTRAINT CK_PRODUCT_ACTIVE CHECK (ACTIVE IN ('Y', 'N'))
);

CREATE TABLE RPGBA_CC.ORDER_HEADER (
    -- Seed orders use explicit IDs in the 5000 range. Generated learner orders
    -- start at 6001 so the identity sequence cannot collide with that baseline.
    ORDER_ID         BIGINT       GENERATED BY DEFAULT AS IDENTITY
                                  (START WITH 6001 INCREMENT BY 1) NOT NULL,
    CUSTOMER_ID      INTEGER      NOT NULL,
    ORDER_TIMESTAMP  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ORDER_STATUS     VARCHAR(12)  NOT NULL DEFAULT 'OPEN',
    CONSTRAINT PK_ORDER_HEADER PRIMARY KEY (ORDER_ID),
    CONSTRAINT FK_ORDER_CUSTOMER FOREIGN KEY (CUSTOMER_ID)
        REFERENCES RPGBA_CC.CUSTOMER (CUSTOMER_ID),
    CONSTRAINT CK_ORDER_STATUS CHECK
        (ORDER_STATUS IN ('OPEN', 'SUBMITTED', 'CANCELLED', 'FULFILLED'))
);

CREATE TABLE RPGBA_CC.ORDER_ITEM (
    ORDER_ID      BIGINT       NOT NULL,
    LINE_NO       SMALLINT     NOT NULL,
    PRODUCT_ID    INTEGER      NOT NULL,
    QUANTITY      INTEGER      NOT NULL,
    UNIT_PRICE    DECIMAL(9,2) NOT NULL,
    CONSTRAINT PK_ORDER_ITEM PRIMARY KEY (ORDER_ID, LINE_NO),
    CONSTRAINT FK_ITEM_ORDER FOREIGN KEY (ORDER_ID)
        REFERENCES RPGBA_CC.ORDER_HEADER (ORDER_ID),
    CONSTRAINT FK_ITEM_PRODUCT FOREIGN KEY (PRODUCT_ID)
        REFERENCES RPGBA_CC.PRODUCT (PRODUCT_ID),
    CONSTRAINT CK_ITEM_QTY CHECK (QUANTITY > 0),
    CONSTRAINT CK_ITEM_PRICE CHECK (UNIT_PRICE >= 0)
);

COMMENT ON TABLE RPGBA_CC.PRODUCT IS
    'Academy Coffee Company product facts used by Module 2 and later modules';

COMMENT ON COLUMN RPGBA_CC.PRODUCT.QUANTITY_AVAILABLE IS
    'Current training quantity fact; not an order-approval decision';

-- Validation queries. These are read-only.
SELECT TABLE_SCHEMA, TABLE_NAME, TABLE_TYPE
  FROM QSYS2.SYSTABLES
 WHERE TABLE_SCHEMA = 'RPGBA_CC'
   AND TABLE_NAME IN ('CUSTOMER', 'PRODUCT', 'ORDER_HEADER', 'ORDER_ITEM')
 ORDER BY TABLE_NAME;
